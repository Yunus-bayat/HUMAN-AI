"""Generate figures and LaTeX tables for HUMAN-AI paper (organic sample only).

Usage:
    python experiments/generate_paper_figures.py

Outputs:
    paper/figures/fig_rq1_source_vs_llm.pdf
    paper/figures/fig_rq2_distribution.pdf
    paper/figures/fig_rq3_bug_effect.pdf
    paper/figures/fig_pipeline.pdf
    paper/figures/table_summary.tex
    paper/figures/stats.json
"""

from __future__ import annotations

import json
import os
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "figures"
OUT.mkdir(parents=True, exist_ok=True)

# Organic cutoff: simulated batches started Aug 7 2026 ~06:39 UTC
SIM_START = datetime(2026, 8, 7, 6, 39, 0)

LABELS = {
    "original": "Source Code",
    "chatgpt": "ChatGPT",
    "groq": "Groq",
    "gemini": "Gemini",
    "claude": "Claude",
}

COLORS = {
    "original": "#64748b",
    "chatgpt": "#10a37f",
    "groq": "#f97316",
    "gemini": "#4285f4",
    "claude": "#d97757",
}


def load_organic_rows():
    sys.path.insert(0, str(ROOT / "experiments"))
    from dotenv import load_dotenv

    load_dotenv(ROOT / ".env")
    from results_store import _pg_conn, ensure_schema

    ensure_schema()
    with _pg_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT c.chosen_source, c.has_injected_bug
                FROM survey_choices c
                JOIN (
                    SELECT response_id, MIN(timestamp) AS started
                    FROM survey_choices
                    GROUP BY response_id
                ) s ON c.response_id = s.response_id
                WHERE s.started < %s
                """,
                (SIM_START,),
            )
            return [dict(r) for r in cur.fetchall()]


def compute_stats(rows):
    by = Counter(r["chosen_source"] for r in rows)
    total = len(rows)
    n_part = total // 5 if total else 0
    src = by.get("original", 0)
    llm = total - src
    buggy = [r for r in rows if r.get("has_injected_bug")]
    clean = [r for r in rows if not r.get("has_injected_bug")]
    bs = sum(1 for r in buggy if r["chosen_source"] == "original")
    cs = sum(1 for r in clean if r["chosen_source"] == "original")
    expected = total / 5 if total else 1
    chi2 = sum((by.get(k, 0) - expected) ** 2 / expected for k in LABELS)
    return {
        "participants": n_part,
        "total_choices": total,
        "source_count": src,
        "source_pct": round(src / total * 100, 1) if total else 0,
        "llm_count": llm,
        "llm_pct": round(llm / total * 100, 1) if total else 0,
        "by_source": {k: by.get(k, 0) for k in LABELS},
        "by_source_pct": {k: round(by.get(k, 0) / total * 100, 1) if total else 0 for k in LABELS},
        "buggy_n": len(buggy),
        "buggy_source_rate": round(bs / len(buggy) * 100, 1) if buggy else 0,
        "clean_n": len(clean),
        "clean_source_rate": round(cs / len(clean) * 100, 1) if clean else 0,
        "chi2_uniform": round(chi2, 2),
    }


def write_latex_table(stats, path):
    lines = [
        "% Auto-generated by experiments/generate_paper_figures.py",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Summary statistics (organic sample, $N={stats['participants']}$ participants, "
        f"{stats['total_choices']} decisions).}}",
        "\\label{tab:summary}",
        "\\begin{tabular}{lrr}",
        "\\toprule",
        "\\textbf{Metric} & \\textbf{Count} & \\textbf{\\%} \\\\",
        "\\midrule",
        f"LLM (aggregate) & {stats['llm_count']} & {stats['llm_pct']} \\\\",
        f"Source code & {stats['source_count']} & {stats['source_pct']} \\\\",
        "\\midrule",
    ]
    for key in ("chatgpt", "gemini", "claude", "groq", "original"):
        c = stats["by_source"][key]
        p = stats["by_source_pct"][key]
        lines.append(f"{LABELS[key]} & {c} & {p} \\\\")
    lines += [
        "\\midrule",
        f"Bugs present $\\rightarrow$ source rate & \\multicolumn{{2}}{{r}}{{{stats['buggy_source_rate']}\\% ($n={stats['buggy_n']}$)}} \\\\",
        f"Clean $\\rightarrow$ source rate & \\multicolumn{{2}}{{r}}{{{stats['clean_source_rate']}\\% ($n={stats['clean_n']}$)}} \\\\",
        f"$\\chi^2$ vs. uniform & \\multicolumn{{2}}{{r}}{{{stats['chi2_uniform']} (n.s.)}} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot_figures(stats):
    try:
        import matplotlib.pyplot as plt
        from matplotlib.patches import FancyBboxPatch
    except ImportError:
        print("matplotlib not installed; run: pip install matplotlib")
        return

    plt.rcParams.update({
        "font.size": 10,
        "figure.dpi": 150,
        "savefig.bbox": "tight",
    })

    # RQ1: Source vs LLM pie
    fig, ax = plt.subplots(figsize=(4, 4))
    ax.pie(
        [stats["llm_count"], stats["source_count"]],
        labels=[f"LLM\n{stats['llm_pct']}%", f"Source\n{stats['source_pct']}%"],
        colors=["#6366f1", "#64748b"],
        autopct="",
        startangle=90,
        wedgeprops={"edgecolor": "white", "linewidth": 1.5},
    )
    ax.set_title("RQ1: Source vs. LLM Trust")
    fig.savefig(OUT / "fig_rq1_source_vs_llm.pdf")
    fig.savefig(OUT / "fig_rq1_source_vs_llm.png")
    plt.close(fig)

    # RQ2: Five-way bar chart
    keys = list(LABELS.keys())
    counts = [stats["by_source"][k] for k in keys]
    colors = [COLORS[k] for k in keys]
    labels = [LABELS[k] for k in keys]

    fig, ax = plt.subplots(figsize=(6, 3.5))
    bars = ax.bar(labels, counts, color=colors, edgecolor="white", linewidth=0.8)
    ax.set_ylabel("Selections")
    ax.set_title("RQ2: Trust Distribution Across Five Options")
    ax.axhline(stats["total_choices"] / 5, color="#94a3b8", linestyle="--", linewidth=1, label="Uniform expected")
    for bar, c in zip(bars, counts):
        pct = round(c / stats["total_choices"] * 100, 1)
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.8, f"{pct}%", ha="center", va="bottom", fontsize=8)
    ax.legend(fontsize=8)
    plt.xticks(rotation=15, ha="right")
    fig.savefig(OUT / "fig_rq2_distribution.pdf")
    fig.savefig(OUT / "fig_rq2_distribution.png")
    plt.close(fig)

    # RQ3: Bug effect
    fig, ax = plt.subplots(figsize=(4, 3.5))
    conditions = ["Bug injected", "Clean"]
    rates = [stats["buggy_source_rate"], stats["clean_source_rate"]]
    ns = [stats["buggy_n"], stats["clean_n"]]
    bars = ax.bar(conditions, rates, color=["#ef4444", "#22c55e"], edgecolor="white")
    ax.set_ylabel("Source selection rate (%)")
    ax.set_title("RQ3: Source Trust — Buggy vs. Clean")
    ax.set_ylim(0, max(rates) * 1.35 + 5)
    for bar, rate, n in zip(bars, rates, ns):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.8, f"{rate}%\n(n={n})", ha="center", va="bottom", fontsize=9)
    fig.savefig(OUT / "fig_rq3_bug_effect.pdf")
    fig.savefig(OUT / "fig_rq3_bug_effect.png")
    plt.close(fig)

    # Pipeline diagram
    fig, ax = plt.subplots(figsize=(7, 1.8))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 2)
    ax.axis("off")
    steps = [
        ("52 Java\nsnippets", "#e0e7ff"),
        ("Bug inject\n(20/52)", "#fecaca"),
        ("LLM refactor\n(×4)", "#bbf7d0"),
        ("Web survey\n(5 Q)", "#fde68a"),
        ("Analysis", "#ddd6fe"),
    ]
    x = 0.3
    w = 1.6
    for i, (text, color) in enumerate(steps):
        box = FancyBboxPatch(
            (x, 0.5), w, 1.0,
            boxstyle="round,pad=0.05,rounding_size=0.08",
            facecolor=color, edgecolor="#334155", linewidth=1,
        )
        ax.add_patch(box)
        ax.text(x + w / 2, 1.0, text, ha="center", va="center", fontsize=8, fontweight="bold")
        if i < len(steps) - 1:
            ax.annotate("", xy=(x + w + 0.15, 1.0), xytext=(x + w + 0.02, 1.0),
                        arrowprops=dict(arrowstyle="->", color="#334155", lw=1.5))
        x += w + 0.25
    ax.set_title("HUMAN-AI Study Pipeline", fontsize=11, fontweight="bold", pad=8)
    fig.savefig(OUT / "fig_pipeline.pdf")
    fig.savefig(OUT / "fig_pipeline.png")
    plt.close(fig)


def main():
    rows = load_organic_rows()
    if not rows:
        print("No organic rows found. Check DATABASE_URL in .env")
        sys.exit(1)
    stats = compute_stats(rows)
    (OUT / "stats.json").write_text(json.dumps(stats, indent=2), encoding="utf-8")
    write_latex_table(stats, OUT / "table_summary.tex")
    plot_figures(stats)
    print(f"Generated figures in {OUT}")
    print(json.dumps(stats, indent=2))


if __name__ == "__main__":
    main()
